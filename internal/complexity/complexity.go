// Package complexity содержит маленькие функции, на которых удобно считать шаги.
package complexity

import "fmt"

// Measurement хранит результат функции и число основных операций.
// В реальной программе мы обычно не добавляем такой счётчик: здесь он нужен,
// чтобы ученица увидела связь между кодом, размером входа n и обозначением O(...).
type Measurement struct {
	Value int
	Steps int
}

// At возвращает элемент по индексу.
//
// Что происходит:
//  1. Проверяем, существует ли индекс.
//  2. Если индекс корректен, сразу обращаемся к нужной ячейке среза.
//
// Для среза обращение по индексу не требует обходить предыдущие элементы,
// поэтому время этой операции считаем O(1). Дополнительная память — O(1).
//
// Как не нужно: нельзя писать values[index] до проверки границ. При index < 0
// или index >= len(values) программа завершится с panic.
func At(values []int, index int) (int, bool) {
	if index < 0 || index >= len(values) {
		return 0, false
	}
	return values[index], true
}

// Sum последовательно складывает все значения и считает сложения.
//
// Если длина среза равна n, цикл выполняется n раз: время O(n).
// Переменные sum и steps не растут вместе с n: дополнительная память O(1).
//
// Как не нужно: два последовательных цикла по n элементов дают O(2n),
// которое сокращают до O(n), но вложенный цикл — уже не то же самое.
func Sum(values []int) Measurement {
	measurement := Measurement{}
	for _, value := range values {
		measurement.Value += value
		measurement.Steps++
	}
	return measurement
}

// HalvingSteps считает, сколько раз нужно делить положительное n примерно пополам,
// пока не останется один элемент. Так ведёт себя поиск, который каждый раз
// отбрасывает половину вариантов: число шагов растёт как O(log n).
//
// Для n <= 1 ни одного деления не требуется.
//
// Как не нужно: log n не означает «в цикле есть деление». Важно, что размер
// оставшейся задачи на каждом шаге уменьшается в постоянное число раз.
func HalvingSteps(n int) int {
	steps := 0
	for n > 1 {
		n = (n + 1) / 2
		steps++
	}
	return steps
}

// PairComparisons считает все уникальные пары элементов.
//
// Внешний цикл выбирает первый элемент, внутренний — каждый следующий.
// Число сравнений равно n*(n-1)/2. Постоянные коэффициенты в Big O не пишут,
// поэтому время обозначают O(n²). Дополнительная память остаётся O(1).
//
// Как не нужно: видеть два цикла и автоматически писать O(n²). Если циклы идут
// один после другого, а не вложены, обычно получается O(n)+O(n)=O(n).
func PairComparisons(values []int) int {
	steps := 0
	for first := 0; first < len(values); first++ {
		for second := first + 1; second < len(values); second++ {
			steps++
		}
	}
	return steps
}

// Example возвращает короткий предсказуемый результат для cmd и integration-теста.
func Example() string {
	values := []int{10, 20, 30, 40}
	last, _ := At(values, 3)
	sum := Sum(values)
	return fmt.Sprintf("O(1): value=%d; O(n): sum=%d steps=%d; O(log n): steps=%d; O(n²): pairs=%d",
		last, sum.Value, sum.Steps, HalvingSteps(16), PairComparisons(values))
}
